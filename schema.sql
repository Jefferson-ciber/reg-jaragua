-- Portal Regional Jaraguá — executar no SQL Editor do Supabase.
-- Cria perfis, conteúdo interno e políticas de acesso (RLS).
create table if not exists public.member_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  role text not null default 'member' check (role in ('admin','member')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.portal_content (
  id bigint generated by default as identity primary key,
  category text not null default 'Comunicado',
  title text not null,
  body text not null,
  sort_order integer not null default 100,
  is_published boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.member_profiles enable row level security;
alter table public.portal_content enable row level security;
revoke all on public.member_profiles from anon, authenticated;
revoke all on public.portal_content from anon, authenticated;
grant select on public.member_profiles to authenticated;
grant select on public.portal_content to authenticated;
grant insert, update, delete on public.portal_content to authenticated;

-- Funções SECURITY DEFINER para consultar perfil sem recursão nas políticas.
create or replace function public.current_member_is_active()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.member_profiles p where p.id = (select auth.uid()) and p.is_active = true)
$$;
create or replace function public.current_member_is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.member_profiles p where p.id = (select auth.uid()) and p.is_active = true and p.role = 'admin')
$$;
revoke all on function public.current_member_is_active() from public;
revoke all on function public.current_member_is_admin() from public;
grant execute on function public.current_member_is_active() to authenticated;
grant execute on function public.current_member_is_admin() to authenticated;

create policy "profile owner or active admin can read profiles"
on public.member_profiles for select to authenticated
using (id = (select auth.uid()) or (select public.current_member_is_admin()));

create policy "active members can read published content"
on public.portal_content for select to authenticated
using ((select public.current_member_is_active()) and is_published = true);
create policy "admins can add content"
on public.portal_content for insert to authenticated
with check ((select public.current_member_is_admin()) and created_by = (select auth.uid()));
create policy "admins can update content"
on public.portal_content for update to authenticated
using ((select public.current_member_is_admin()))
with check ((select public.current_member_is_admin()));
create policy "admins can delete content"
on public.portal_content for delete to authenticated
using ((select public.current_member_is_admin()));

