-- ──────────────────────────────────────────────
-- Tabela: activity_log
-- ──────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.activity_log (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id    uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  subject_id  uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  action_type text NOT NULL
    CHECK (action_type IN (
      'member_created', 'grade_changed', 'cargo_changed',
      'division_changed', 'honor_awarded', 'event_created',
      'participation_recorded', 'travel_started', 'travel_ended',
      'help_requested', 'comunicado_created', 'comunicado_updated'
    )),
  description text NOT NULL DEFAULT '',
  payload     jsonb,
  created_at  timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.activity_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.activity_log FROM anon, authenticated;
GRANT SELECT, INSERT ON public.activity_log TO authenticated;

DROP POLICY IF EXISTS "admins or actor can read activity_log" ON public.activity_log;
CREATE POLICY "admins or actor can read activity_log"
ON public.activity_log FOR SELECT TO authenticated
USING (
  actor_id = (SELECT auth.uid())
  OR (SELECT public.current_member_is_admin())
);

DROP POLICY IF EXISTS "active members can insert activity_log" ON public.activity_log;
CREATE POLICY "active members can insert activity_log"
ON public.activity_log FOR INSERT TO authenticated
WITH CHECK (
  (SELECT public.current_member_is_active())
  AND actor_id = (SELECT auth.uid())
);

-- ──────────────────────────────────────────────
-- Tabela: travel_protocols
-- ──────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.travel_protocols (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id       uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  destination     text NOT NULL,
  departure_date  date NOT NULL,
  return_date     date,
  route_notes     text,
  vehicle_info    text,
  status          text NOT NULL DEFAULT 'planned'
    CHECK (status IN ('planned', 'in_progress', 'completed', 'cancelled')),
  registered_by   uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT travel_return_after_departure
    CHECK (return_date IS NULL OR return_date >= departure_date)
);

ALTER TABLE public.travel_protocols ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.travel_protocols FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.travel_protocols TO authenticated;

DROP POLICY IF EXISTS "member can read own travels or admin reads all" ON public.travel_protocols;
CREATE POLICY "member can read own travels or admin reads all"
ON public.travel_protocols FOR SELECT TO authenticated
USING (
  member_id = (SELECT auth.uid())
  OR (SELECT public.current_member_is_admin())
);

DROP POLICY IF EXISTS "active member can insert own travel" ON public.travel_protocols;
CREATE POLICY "active member can insert own travel"
ON public.travel_protocols FOR INSERT TO authenticated
WITH CHECK (
  (SELECT public.current_member_is_active())
  AND member_id = (SELECT auth.uid())
);

DROP POLICY IF EXISTS "member can update own travel or admin updates any" ON public.travel_protocols;
CREATE POLICY "member can update own travel or admin updates any"
ON public.travel_protocols FOR UPDATE TO authenticated
USING (
  member_id = (SELECT auth.uid())
  OR (SELECT public.current_member_is_admin())
);

DROP POLICY IF EXISTS "member can delete own travel or admin deletes any" ON public.travel_protocols;
CREATE POLICY "member can delete own travel or admin deletes any"
ON public.travel_protocols FOR DELETE TO authenticated
USING (
  member_id = (SELECT auth.uid())
  OR (SELECT public.current_member_is_admin())
);

-- ──────────────────────────────────────────────
-- Tabela: travel_emergencies
-- ──────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.travel_emergencies (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  travel_id       bigint REFERENCES public.travel_protocols(id) ON DELETE SET NULL,
  member_id       uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  latitude        numeric(10, 7),
  longitude       numeric(10, 7),
  location_text   text,
  description     text NOT NULL DEFAULT '',
  severity        text NOT NULL DEFAULT 'high'
    CHECK (severity IN ('low', 'medium', 'high', 'critical')),
  status          text NOT NULL DEFAULT 'active'
    CHECK (status IN ('active', 'acknowledged', 'resolved')),
  resolved_at     timestamptz,
  resolved_by     uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.travel_emergencies ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.travel_emergencies FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON public.travel_emergencies TO authenticated;

DROP POLICY IF EXISTS "member sees own emergencies or admin sees all" ON public.travel_emergencies;
CREATE POLICY "member sees own emergencies or admin sees all"
ON public.travel_emergencies FOR SELECT TO authenticated
USING (
  member_id = (SELECT auth.uid())
  OR (SELECT public.current_member_is_admin())
);

DROP POLICY IF EXISTS "active member can insert emergency" ON public.travel_emergencies;
CREATE POLICY "active member can insert emergency"
ON public.travel_emergencies FOR INSERT TO authenticated
WITH CHECK (
  (SELECT public.current_member_is_active())
  AND member_id = (SELECT auth.uid())
);

DROP POLICY IF EXISTS "admin can update emergency status" ON public.travel_emergencies;
CREATE POLICY "admin can update emergency status"
ON public.travel_emergencies FOR UPDATE TO authenticated
USING ((SELECT public.current_member_is_admin()));

