-- Dados iniciais dos graus (só insere os que ainda não existem pelo nome)
DO $$
DECLARE
  seq_exists boolean;
BEGIN
  -- Garante que a coluna id tem uma sequência (caso a tabela tenha sido criada sem IDENTITY)
  SELECT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'grades'
      AND column_name = 'id' AND column_default LIKE 'nextval%'
  ) INTO seq_exists;

  IF NOT seq_exists THEN
    -- Cria sequência e associa
    CREATE SEQUENCE IF NOT EXISTS public.grades_id_seq;
    ALTER TABLE public.grades ALTER COLUMN id SET DEFAULT nextval('public.grades_id_seq');
    -- Sincroniza com o maior id existente
    PERFORM setval('public.grades_id_seq', COALESCE((SELECT MAX(id) FROM public.grades), 0) + 1, false);
  END IF;
END $$;

