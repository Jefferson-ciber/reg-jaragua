CREATE OR REPLACE FUNCTION public.set_member_cargo(
  p_member uuid, p_cargo integer,
  p_date date DEFAULT CURRENT_DATE, p_note text DEFAULT NULL
) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE old_cargo integer;
BEGIN
  IF NOT (SELECT public.current_member_is_admin()) THEN RAISE EXCEPTION 'Permissão negada.'; END IF;
  SELECT cargo_id INTO old_cargo FROM public.member_profiles WHERE id = p_member;
  UPDATE public.member_profiles SET cargo_id = p_cargo, updated_at = now() WHERE id = p_member;
  INSERT INTO public.cargo_history (member_id, from_cargo_id, to_cargo_id, note, changed_by, effective_date)
  VALUES (p_member, old_cargo, p_cargo, p_note, (SELECT auth.uid()), COALESCE(p_date, CURRENT_DATE));
END;
$$;

